def text_size(text, scale):
    """Pixel (width, height) of a string rendered at a given scale."""
    if not text:
        return 0, 0
    return (len(text) * 6 - 1) * scale, 7 * scale


def draw_text(pixels, img_w, img_h, text, x, y, color, scale=1):
    """Blit a string into a flat RGB pixel buffer (list of bytearrays)."""
    cursor = x
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit != "1":
                    continue
                for sy in range(scale):
                    py = y + gy * scale + sy
                    if not 0 <= py < img_h:
                        continue
                    row_px = pixels[py]
                    for sx in range(scale):
                        px = cursor + gx * scale + sx
                        if 0 <= px < img_w:
                            off = px * 3
                            row_px[off:off + 3] = bytes(color)
        cursor += 6 * scale
